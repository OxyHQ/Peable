const CATALOGS: Readonly<Record<string, Readonly<Record<string, string>>>> = { en, es };

/** The catalog `t` reads first; English fills any key it lacks. */
let activeLocale = FALLBACK_LOCALE;

/** A catalog by language (`es-ES` reads `es`), for tests and the locale switch. */
export function catalogFor(locale: string): Readonly<Record<string, string>> | undefined {
  return CATALOGS[locale.split('-')[0]?.toLowerCase() ?? ''];
}

const listeners = new Set<() => void>();

/**
 * Switch the catalog `t` reads; an unknown language selects English. Returns
 * the one chosen, and tells every `useLocale()` when it changed.
 */
export function setLocale(locale: string | null | undefined): string {
  const language = (locale ?? '').split('-')[0]?.toLowerCase() ?? '';
  const next = Object.hasOwn(CATALOGS, language) ? language : FALLBACK_LOCALE;
  if (next !== activeLocale) {
    activeLocale = next;
    for (const listener of listeners) listener();
  }
  return activeLocale;
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** The active language, re-rendering the caller when it changes. */
export function useLocale(): string {
  return useSyncExternalStore(subscribe, getLocale, getLocale);
}

/** The language `t` reads now (`en`, `es`) — what dates are formatted in. */
export function getLocale(): string {
  return activeLocale;
}

export type TranslationParams = Record<string, string | number>;

/** The string for `key` in the active locale (else English), with `{name}` placeholders filled. Unknown keys render as the key. */
export function t(key: string, params?: TranslationParams): string {
  const template = CATALOGS[activeLocale]?.[key] ?? en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(params, name) ? String(params[name]) : match,
  );
}

/**
 * The words for one value of a vocabulary (`paymentStatus.succeeded`), or the
 * raw value itself when no catalog has a key for it — a status the gateway
 * added after this build still shows, as its identifier.
 */
export function labelFor(prefix: string, value: string): string {
  const key = `${prefix}.${value}`;
  const label = t(key);
  return label === key ? value : label;
}
