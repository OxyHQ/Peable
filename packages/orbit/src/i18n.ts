/**
 * Orbit's own words, in English and Spanish.
 *
 * WHICH language is Oxy's decision, never Orbit's (Oxy ADR 0022): `OxyProvider`
 * resolves it — the account's primary language when signed in, else a guest
 * choice, else the device or browser — coerces it to `SUPPORTED_LOCALES`, and
 * calls `setLocale` (its `language.onChange`, `app/_layout.tsx`). The
 * Settings switcher changes the ACCOUNT's language through Oxy, and this
 * follows. Nothing here stores a language of its own.
 *
 * A flat dictionary with `{name}` placeholders rather than react-i18next: no
 * string needs plural rules, and the catalogs are small enough to ship whole.
 * `useLocale()` re-renders the tree when the language changes (the root keys
 * the screens by it), because `t` itself is a plain function.
 *
 * `i18n.test.ts` checks that every key has both languages with the same
 * placeholders. `t` still falls back to English per key, so a key added in
 * English only renders, in English, rather than as its name.
 */
