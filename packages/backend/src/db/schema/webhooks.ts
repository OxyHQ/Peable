import { sql } from 'drizzle-orm';
import {
  boolean,
  check,
  index,
  integer,
  jsonb,
  pgTable,
  text,
  uniqueIndex,
} from 'drizzle-orm/pg-core';
import { createdAt, generatedId, inList, timestamptz, updatedAt } from '@oxy.so/db';
import { events } from './events';
import { merchants } from './merchants';
import {
  WEBHOOK_DELIVERY_STATUSES,
  WEBHOOK_ENABLED_EVENTS,
  WEBHOOK_ENDPOINT_DISABLED_REASONS,
  WEBHOOK_ENDPOINT_STATUSES,
} from './valueSets';

/** The URL bound `safeFetch` itself enforces (`MAX_URL_LENGTH`). */
const WEBHOOK_URL_MAX = 2048;
/** Stripe's bound on an endpoint's description. */
export const WEBHOOK_ENDPOINT_DESCRIPTION_MAX = 5000;

/**
 * A webhook endpoint (`we_…`) — one URL a merchant receives events at
 * (ADR 0014 D4). Replaces `merchants.webhook_url` / `webhook_secret`: a
 * merchant now holds up to `WEBHOOK_ENDPOINTS_MAX_PER_MERCHANT` (16), each
 * with its own event filter and its own secret.
 *
 * ## The secret
 *
 * `whsec_…`, GENERATED by Peable (`services/webhookEndpoints.ts`), never chosen
 * by the merchant — a merchant-chosen secret is as strong as the merchant's
 * imagination. Returned on the create and on a roll, and never again: it is a
 * protected column (`db/protectedColumns.ts`), so no ordinary read selects it.
 * Stored as the HMAC key itself, because signing needs the key; it is never
 * logged and never on a DTO.
 *
 * A roll moves the current secret to `previous_secret` with an expiry (≤ 24h).
 * Until then every delivery is signed with BOTH (two `v1=`), so a receiver can
 * switch keys without a window in which it refuses Peable.
 *
 * ## Disabling, and the three-day rule
 *
 * `failing_since` is the start of the endpoint's current run of failed
 * attempts; any delivered attempt clears it. An attempt that fails when the run
 * is three days old disables the endpoint with `disabled_reason =
 * 'delivery_failures'` — `recordEndpointAttempt` does both in one statement,
 * so two dispatchers cannot disagree about it.
 */
export const webhookEndpoints = pgTable(
  'webhook_endpoints',
  {
    id: generatedId(),
    /** The public `we_…`. */
    publicId: text().notNull(),
    merchantId: text()
      .notNull()
      .references(() => merchants.id, { onDelete: 'restrict' }),
    url: text().notNull(),
    description: text(),
    /** Event types delivered here; `*` is every type. Never empty. */
    enabledEvents: text().array().notNull(),
    metadata: jsonb().$type<Record<string, string>>().notNull().default(sql`'{}'::jsonb`),
    /** The wire version events are rendered with for this endpoint. */
    apiVersion: text().notNull(),
    secret: text().notNull(),
    previousSecret: text(),
    previousSecretExpiresAt: timestamptz(),
    status: text().notNull().default('enabled'),
    disabledReason: text(),
    failingSince: timestamptz(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    uniqueIndex('webhook_endpoints_public_id_key').on(table.publicId),
    /** The fan-out reads one merchant's endpoints inside every money transaction. */
    index('webhook_endpoints_merchant_id_idx').on(table.merchantId),
    check(
      'webhook_endpoints_status_check',
      sql.raw(`status in (${inList(WEBHOOK_ENDPOINT_STATUSES)})`),
    ),
    check(
      'webhook_endpoints_disabled_reason_check',
      sql.raw(
        `disabled_reason is null or disabled_reason in (${inList(WEBHOOK_ENDPOINT_DISABLED_REASONS)})`,
      ),
    ),
    /** A disabled endpoint says why; an enabled one has nothing to say. */
    check(
      'webhook_endpoints_disabled_reason_agrees_check',
      sql`(${table.status} = 'disabled') = (${table.disabledReason} is not null)`,
    ),
    /**
     * Never empty, and only subscribable types or `*`. `<@` is "contained in",
     * so an unknown type — or the targeted `webhook_endpoint.test` — is refused
     * here even if a writer skipped the route's validation.
     */
    check(
      'webhook_endpoints_enabled_events_check',
      sql.raw(
        `cardinality(enabled_events) >= 1 and enabled_events <@ ARRAY[${inList(WEBHOOK_ENABLED_EVENTS)}]::text[]`,
      ),
    ),
    check(
      'webhook_endpoints_url_check',
      sql.raw(`url ~ '^https?://' and char_length(url) <= ${WEBHOOK_URL_MAX}`),
    ),
    check(
      'webhook_endpoints_description_check',
      sql.raw(
        `description is null or char_length(description) between 1 and ${WEBHOOK_ENDPOINT_DESCRIPTION_MAX}`,
      ),
    ),
    check('webhook_endpoints_metadata_check', sql`jsonb_typeof(${table.metadata}) = 'object'`),
    check(
      'webhook_endpoints_api_version_check',
      sql.raw(`api_version ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'`),
    ),
    /**
     * Non-empty, and no stricter: a secret Peable generates is `whsec_…`, but
     * the endpoints created from `merchants.webhook_secret` by the migration
     * that introduced this table carry the merchant's own value byte for byte,
     * so their receivers keep verifying. Rolling one replaces it with a
     * generated secret.
     */
    check('webhook_endpoints_secret_check', sql`char_length(${table.secret}) >= 1`),
    /** A rolled secret always carries the moment it stops signing, and only then. */
    check(
      'webhook_endpoints_previous_secret_agrees_check',
      sql`(${table.previousSecret} is null) = (${table.previousSecretExpiresAt} is null)`,
    ),
  ],
);

/**
 * One webhook delivery — ONE event sent to ONE endpoint (ADR 0014 D4), and the
 * DURABLE PROMISE that it will be attempted (ADR 0001 D7).
 *
 * Rows are written by `recordEvent`'s fan-out in the SAME TRANSACTION as the
 * change that caused the event, one per enabled endpoint whose
 * `enabled_events` matches, and claimed afterwards by the dispatcher
 * (`services/webhookOutbox.ts`). That ordering is the whole point — an event
 * that exists only in memory between the commit and the HTTP call is an event
 * a crash loses.
 *
 * The body is not stored here. It is the event (`event_id`), rendered at
 * attempt time from the stored snapshot — which never changes, so every
 * attempt and every redelivery sends the same bytes apart from the signature.
 */
export const webhookDeliveries = pgTable(
  'webhook_deliveries',
  {
    id: generatedId(),
    merchantId: text()
      .notNull()
      .references(() => merchants.id, { onDelete: 'restrict' }),
    /** The event delivered. Deleting the event (30-day retention) deletes this row. */
    eventId: text()
      .notNull()
      .references(() => events.id, { onDelete: 'cascade' }),
    /**
     * The endpoint it is sent to. `cascade`: a deleted endpoint takes its
     * deliveries with it — pending ones included, which is what deleting an
     * endpoint means.
     */
    endpointId: text()
      .notNull()
      .references(() => webhookEndpoints.id, { onDelete: 'cascade' }),
    /**
     * The URL actually POSTed to, as of the latest attempt.
     *
     * Re-read from the endpoint on every attempt rather than frozen at enqueue:
     * a retry should reach where the endpoint IS, not where it was when the
     * payment settled.
     */
    url: text().notNull(),
    attempts: integer().notNull().default(0),
    delivered: boolean().notNull().default(false),
    lastStatus: text().notNull().default('pending'),
    /** Why the last attempt did not succeed. Operator-facing; never a secret. */
    lastError: text(),
    /**
     * When this row becomes claimable. NULL exactly when the row is terminal.
     *
     * Set to "now" at enqueue so the first attempt is immediate, and pushed out
     * by the backoff schedule after each transient failure.
     */
    nextAttemptAt: timestamptz(),
    /**
     * The lease. A dispatcher pass claims a row by stamping both of these, and
     * releases them when it records the outcome. Both or neither, always
     * (`webhook_deliveries_lease_agrees_check`): the expiry is what makes a
     * dispatcher that died mid-attempt recoverable.
     */
    leaseOwner: text(),
    leaseExpiresAt: timestamptz(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    index('webhook_deliveries_merchant_id_idx').on(table.merchantId),
    /** The cascade from an event, and "the deliveries of this event". */
    index('webhook_deliveries_event_id_idx').on(table.eventId),
    /** The cascade from an endpoint, and its delivery log. */
    index('webhook_deliveries_endpoint_id_idx').on(table.endpointId),
    /**
     * The dispatcher's claim query: due, pending, unleased. Partial, on
     * `next_attempt_at` — NULL for every terminal row — so the index holds
     * only the work queue rather than the whole delivery history.
     */
    index('webhook_deliveries_due_idx')
      .on(table.nextAttemptAt)
      .where(sql`${table.nextAttemptAt} is not null`),
    check(
      'webhook_deliveries_last_status_check',
      sql.raw(`last_status in (${inList(WEBHOOK_DELIVERY_STATUSES)})`),
    ),
    /** Zero is the normal starting value: a row exists BEFORE any attempt. */
    check('webhook_deliveries_attempts_check', sql`${table.attempts} >= 0`),
    /**
     * `delivered` and `last_status` are two spellings of one fact, and every
     * writer derives the second from the first.
     */
    check(
      'webhook_deliveries_status_agrees_check',
      sql`${table.delivered} = (${table.lastStatus} = 'delivered')`,
    ),
    /**
     * A row is scheduled exactly when it is pending. A `pending` row with no
     * `next_attempt_at` would never be attempted; a terminal row that kept its
     * schedule would be re-delivered forever.
     */
    check(
      'webhook_deliveries_schedule_agrees_check',
      sql`(${table.lastStatus} = 'pending') = (${table.nextAttemptAt} is not null)`,
    ),
    check(
      'webhook_deliveries_lease_agrees_check',
      sql`(${table.leaseOwner} is null) = (${table.leaseExpiresAt} is null)`,
    ),
    /** A terminal row holds no lease — nothing may claim what is already done. */
    check(
      'webhook_deliveries_terminal_has_no_lease_check',
      sql`${table.lastStatus} = 'pending' or ${table.leaseOwner} is null`,
    ),
  ],
);
